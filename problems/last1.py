import sympy as sp
m,l,g,t=sp.symbols('m l g t',positive=True)
th1,th2=sp.Function('th1')(t),sp.Function('th2')(t)
x1=l*sp.sin(th1); y1=-l*sp.cos(th1)
x2=x1+l*sp.sin(th2); y2=y1-l*sp.cos(th2)
K=sp.Rational(1,2)*m*(sp.diff(x1,t)**2+sp.diff(y1,t)**2+sp.diff(x2,t)**2+sp.diff(y2,t)**2)
U=m*g*(y1+y2+2*l)
# second order: substitute th -> eps*th and expand
e=sp.symbols('eps')
a1,a2,v1,v2=sp.symbols('a1 a2 v1 v2')
K2=sp.series(K.subs({sp.Derivative(th1,t):e*v1,sp.Derivative(th2,t):e*v2}).subs({th1:e*a1,th2:e*a2}),e,0,3).removeO().subs(e,1)
U2=sp.series(U.subs({th1:e*a1,th2:e*a2}),e,0,3).removeO().subs(e,1)
print("K2",sp.expand(K2)); print("U2",sp.expand(U2))
M=sp.hessian(K2,(v1,v2)); Kst=sp.hessian(U2,(a1,a2)); print("M",M,"K",Kst)
w2=sp.symbols('w2'); ch=sp.factor((Kst-w2*M).det()); print("char",ch, sp.solve(ch,w2))
for s in sp.solve(ch,w2):
    v=(Kst-s*M).nullspace()[0]; print("w2",sp.simplify(s)," ratio",sp.simplify(v[1]/v[0]))
# normal coords
a,b,ad,bd=sp.symbols('a b ad bd')
Kab=sp.expand(K2.subs({v1:ad+bd,v2:sp.sqrt(2)*(ad-bd)})); Uab=sp.expand(U2.subs({a1:a+b,a2:sp.sqrt(2)*(a-b)}))
print("Kab",Kab); print("Uab",Uab)
Ia=sp.simplify(Kab.coeff(ad,2)*2); Ib=sp.simplify(Kab.coeff(bd,2)*2); D=sp.simplify(Uab.coeff(a,2)*2)
print("Ia",Ia,"Ib",Ib,"D",D,"cross",Kab.coeff(ad,1).coeff(bd,1),Uab.coeff(a,1).coeff(b,1))
num={m:1,l:1,g:10}
print("nums Ia",sp.N(Ia.subs(num)),"Ib",sp.N(Ib.subs(num)),"D",D.subs(num))
wa=sp.sqrt(D/Ia); wb=sp.sqrt(D/Ib)
print("wa",sp.N(wa.subs(num)),"wb",sp.N(wb.subs(num)),"Ta",sp.N(2*sp.pi/wa.subs(num)),"Tb",sp.N(2*sp.pi/wb.subs(num)),"ratio",sp.simplify(wb/wa),sp.N(wb/wa))
# levers per unit a and b for the lower mass: x2 = l(th1+th2)
print("x2 per a", sp.simplify(1+sp.sqrt(2)), " per b", sp.simplify(1-sp.sqrt(2)))
print("profile a", sp.simplify(1+(1+sp.sqrt(2))**2), " b", sp.simplify(1+(1-sp.sqrt(2))**2))
# (d)
a0=b0=sp.Rational(1,100)
th1d=a0*sp.cos(wa*t)+b0*sp.cos(wb*t); th2d=sp.sqrt(2)*(a0*sp.cos(wa*t)-b0*sp.cos(wb*t))
print("th2dd(0)",sp.N(sp.diff(th2d,t,2).subs(t,0).subs(num))," th1dd(0)",sp.N(sp.diff(th1d,t,2).subs(t,0).subs(num)))
print("x2dd(0)", sp.N(sp.diff(th1d+th2d,t,2).subs(t,0).subs(num)))
print("U0", (sp.Rational(1,2)*D*(a0**2+b0**2)).subs(num), " check", (sp.Rational(1,2)*m*g*l*2*sp.Rational(2,100)**2).subs(num))
